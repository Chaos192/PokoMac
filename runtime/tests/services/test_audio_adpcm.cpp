uint64_t fnv(const std::vector<int16_t>& s) {
    uint64_t h = 0xcbf29ce484222325ull;
    const uint8_t* b = reinterpret_cast<const uint8_t*>(s.data());
    for (size_t i = 0; i < s.size() * 2; i++) h = (h ^ b[i]) * 0x100000001b3ull;   // little-endian hosts (x86-64, arm64)
    return h;
}

// Decodes `samples` samples in pieces of `piece` (the whole when 0), as the renderer's data source does.
std::vector<int16_t> decode(const uint8_t* data, size_t size, const int16_t* coefs, int samples, int piece) {
    using nxrt::audren::AdpcmHelper;
    std::vector<int16_t> out(static_cast<size_t>(samples), 0);
    nxrt::audren::AdpcmLoopContext ctx{};
    const nxrt::audren::Span<const uint8_t> in(data, size);
    const nxrt::audren::Span<const int16_t> c(coefs, 16);
    int done = 0;
    while (done < samples) {
        const int n = piece ? std::min(piece, samples - done) : samples;
        const int got = AdpcmHelper::Decode(nxrt::audren::Span<int16_t>(out.data() + done, static_cast<size_t>(n)), in, 0, samples, done, n, c, ctx);
        CHECK_EQ(got, n);
        if (got <= 0) break;
        done += got;
    }
    return out;
}

