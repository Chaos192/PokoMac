# Ported from AnySwitch by Chaos192 (github.com/Chaos192/AnySwitch).
# Compiles the backdrop blur shader (the cheats overlay's glass panel, src/gfx/extras/backdrop_blur.cpp) with glslc (Vulkan SDK), validates
# it with spirv-val, and writes src/gfx/extras/blur_shaders.inc (a uint32 array). The .inc is committed, so building the runtime does not
# need the SDK. Run: python -I scripts/gen_blur_shaders.py   (exit 1 and no .inc written if the shader fails to compile or validate)
#
# The blur is the dual Kawase blur (Marius Bjorge, "Bandwidth-efficient rendering", SIGGRAPH 2015): each down pass halves the image with
# five bilinear taps (the centre four times, the four diagonals), each up pass doubles it back with eight taps; a few passes give a wide,
# smooth blur for little work. The CPU reference the tests compare it with is tests/cheats_ui/blur_ref.cpp: change both together.
import os, subprocess, sys, tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
glslc = r"C:\VulkanSDK\1.4.363.0\Bin\glslc.exe"
spirv_val = r"C:\VulkanSDK\1.4.363.0\Bin\spirv-val.exe"
out_path = os.path.join(root, "src", "gfx", "extras", "blur_shaders.inc")

BLUR_COMP = r"""#version 450
// One pass of the dual Kawase blur: reads the source level (bilinear, clamp to edge) and writes one texel of the destination level.
layout(local_size_x = 8, local_size_y = 8) in;
layout(set = 0, binding = 0) uniform sampler2D u_src;
layout(set = 0, binding = 1, rgba8) uniform writeonly image2D u_dst;
layout(push_constant) uniform Push {
    vec4 src;   // xy: the source's texel size (1 / its size in texels), z: the tap offset in source texels, w: unused
    vec4 dst;   // xy: the destination's size in texels, zw: the region's origin in destination texels
    vec4 p;     // x: 0 = down, 1 = up; y: unused; zw: the region's size in destination texels
    vec4 lim;   // the source region in source UV (the centres of its edge texels): every tap is clamped into it
} pc;
vec4 tap(vec2 uv) { return texture(u_src, clamp(uv, pc.lim.xy, pc.lim.zw)); }
void main() {
    ivec2 g = ivec2(gl_GlobalInvocationID.xy);
    if (g.x >= int(pc.p.z) || g.y >= int(pc.p.w)) return;
    ivec2 px = g + ivec2(pc.dst.zw);
    if (px.x >= int(pc.dst.x) || px.y >= int(pc.dst.y)) return;
    vec2 uv = (vec2(px) + 0.5) / pc.dst.xy;
    vec2 h = pc.src.xy * pc.src.z;
    vec4 c;
    if (pc.p.x < 0.5) {
        c = tap(uv) * 4.0;
        c += tap(uv - h);
        c += tap(uv + h);
        c += tap(uv + vec2(h.x, -h.y));
        c += tap(uv - vec2(h.x, -h.y));
        c *= 0.125;
    } else {
        c = tap(uv + vec2(-h.x * 2.0, 0.0));
        c += tap(uv + vec2(-h.x, h.y)) * 2.0;
        c += tap(uv + vec2(0.0, h.y * 2.0));
        c += tap(uv + vec2(h.x, h.y)) * 2.0;
        c += tap(uv + vec2(h.x * 2.0, 0.0));
        c += tap(uv + vec2(h.x, -h.y)) * 2.0;
        c += tap(uv + vec2(0.0, -h.y * 2.0));
        c += tap(uv + vec2(-h.x, -h.y)) * 2.0;
        c *= (1.0 / 12.0);
    }
    imageStore(u_dst, px, vec4(c.rgb, 1.0));
}
"""

HEADER = """// GENERATED by scripts/gen_blur_shaders.py: do not edit
// SPIR-V of the backdrop blur (the cheats overlay's glass panel, backdrop_blur.cpp), compiled with glslc -O --target-env=vulkan1.3 from
// the GLSL in scripts/gen_blur_shaders.py and checked with spirv-val --target-env vulkan1.3.
//
// kBackdropBlurComp: compute shader, one pass of the dual Kawase blur. Local size 8 x 8 x 1; dispatch ceil(region / 8).
//   Descriptors: set 0, binding 0, COMBINED_IMAGE_SAMPLER (sampler2D u_src, linear, clamp to edge); binding 1, STORAGE_IMAGE (rgba8,
//     image2D u_dst). Both compute stage.
//   Push constants: 64 bytes, VK_SHADER_STAGE_COMPUTE_BIT.
//     offset 0   vec4 src   xy: the source's texel size (1 / size), z: the tap offset in source texels
//     offset 16  vec4 dst   xy: the destination's size in texels, zw: the region's origin in destination texels
//     offset 32  vec4 p     x: 0 = down (5 taps, the centre weighted 4), 1 = up (8 taps); zw: the region's size in destination texels
//     offset 48  vec4 lim   the source region in source UV, x0 y0 x1 y1 (its edge texels' centres): each tap is clamped into it, so the
//                           region blurs as an image of its own (texels outside it are never read)
//   Writes (rgb, 1) to every destination texel of the region.
"""


def compile_one(name, src_name, text, tmp):
    src = os.path.join(tmp, src_name)
    spv = src + ".spv"
    with open(src, "w", newline="\n") as f:
        f.write(text)
    r = subprocess.run([glslc, "-O", "--target-env=vulkan1.3", "-o", spv, src], capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write(r.stdout + r.stderr)
        return None
    r = subprocess.run([spirv_val, "--target-env", "vulkan1.3", spv], capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write(r.stdout + r.stderr)
        return None
    data = open(spv, "rb").read()
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    lines = []
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    return "static const uint32_t %s[] = {\n%s\n};\n" % (name, "\n".join(lines))


def main():
    with tempfile.TemporaryDirectory(dir=os.environ.get("TEMP")) as tmp:
        body = compile_one("kBackdropBlurComp", "backdrop_blur.comp", BLUR_COMP, tmp)
        if body is None:
            return 1
    with open(out_path, "w", newline="\n") as f:
        f.write(HEADER + "\n" + body)
    print("wrote", out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
