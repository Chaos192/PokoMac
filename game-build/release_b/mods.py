def any_files(d):
    return any(True for _ in walk_rel(d))


def walk_rel(d):
    if not os.path.isdir(d):
        return
    for root, dirs, files in os.walk(d):
        dirs.sort()
        for n in sorted(files):
            yield fwd(os.path.relpath(os.path.join(root, n), d))


def unpack_containers(d):
    """A mod's romfs.bin / exefs.nsp (Ryujinx's containers) unpacked into its romfs/ and exefs/ folders, below what those folders already
    hold (Ryujinx serves loose files over the container's). The containers are removed afterwards."""
    for cat, unpack, sub in (('romfs_bin', read_romfs_image, 'romfs'), ('exefs_nsp', read_pfs0, 'exefs')):
        f = os.path.join(d, cat, cat.replace('_bin', '.bin').replace('_nsp', '.nsp'))
        if not os.path.isfile(f):
            continue
        with open(f, 'rb') as src:
            for rel, data in unpack(src):
                dst = os.path.join(d, sub, *rel.split('/'))
                if not os.path.exists(dst):
                    os.makedirs(os.path.dirname(dst), exist_ok=True)
                    with open(dst, 'wb') as out:
                        out.write(data)
        rmtree(os.path.join(d, cat))


def read_pfs0(f):
    """Yield (name, bytes) of every file of a PFS0 (the ExeFS partition format: 'PFS0', count, string table size, then 0x18-byte
    entries of offset, size and name offset, the names, the data)."""
    head = f.read(0x10)
    if head[:4] != b'PFS0':
        raise ModError('exefs.nsp is not a PFS0 partition.')
    n, strsize = struct.unpack_from('<II', head, 4)
    entries = f.read(0x18 * n)
    names = f.read(strsize)
    base = 0x10 + 0x18 * n + strsize
    for i in range(n):
        off, size, name_off = struct.unpack_from('<QQI', entries, 0x18 * i)
        name = names[name_off:names.index(b'\0', name_off) if b'\0' in names[name_off:] else len(names)].decode('utf-8', 'replace')
        if safe_rel(name) != name or '/' in name:
            raise ModError('exefs.nsp names a file outside itself (%s).' % name)
        f.seek(base + off)
        yield name, f.read(size)


def read_romfs_image(f):
    """Yield (path, bytes) of every file of a RomFS image (header of 0x50: the directory and file tables' offsets and sizes, then the data
    offset; directory entries: parent, sibling, first child directory, first file, hash link, name length, name; file entries: parent,
    sibling, data offset (u64), size (u64), hash link, name length, name)."""
    head = f.read(0x50)
    if len(head) < 0x50 or struct.unpack_from('<Q', head, 0)[0] != 0x50:
        raise ModError('romfs.bin is not a RomFS image.')
    _hs, _dho, _dhs, dmo, dms, _fho, _fhs, fmo, fms, data_off = struct.unpack_from('<10Q', head, 0)
    f.seek(dmo)
    dmeta = f.read(dms)
    f.seek(fmo)
    fmeta = f.read(fms)
    none = 0xFFFFFFFF
    out = []
    todo = [(0, '')]
    seen = set()
    while todo:
        d, prefix = todo.pop()
        if d in seen or d + 0x18 > len(dmeta):
            continue
        seen.add(d)
        _parent, _sib, child, fil, _hl, _nl = struct.unpack_from('<6I', dmeta, d)
        c = child
        while c != none and c + 0x18 <= len(dmeta):
            nl = struct.unpack_from('<I', dmeta, c + 0x14)[0]
            name = dmeta[c + 0x18:c + 0x18 + nl].decode('utf-8', 'replace')
            todo.append((c, prefix + name + '/'))
            c = struct.unpack_from('<I', dmeta, c + 4)[0]
        e = fil
        while e != none and e + 0x20 <= len(fmeta):
            _p, sib, doff, size, _h, nl = struct.unpack_from('<IIQQII', fmeta, e)
            name = fmeta[e + 0x20:e + 0x20 + nl].decode('utf-8', 'replace')
            rel = safe_rel(prefix + name)
            if rel is None or not rel:
                raise ModError('romfs.bin names a file outside itself.')
            out.append((rel, data_off + doff, size))
            e = sib
    for rel, at, size in out:
        f.seek(at)
        yield rel, f.read(size)


def check_mod(title, d):
    """What an installed mod targets in this title: (problems that refuse it, warnings). Code patches and cheats name build ids."""
    problems, warnings = [], []
    bids = title.modules
    patch_files = list(walk_rel(os.path.join(d, 'patches')))
    matched, others = [], set()
    for rel in patch_files:
        p = os.path.join(d, 'patches', *rel.split('/'))
        bid = apply_ips.patch_build_id(p)
        if bid and any(apply_ips.bid_matches(bid, b) for b in bids.values()):
            matched.append(rel)
        else:
            others.add(bid[:16] if bid else rel)
    cheats = list(walk_rel(os.path.join(d, 'cheats')))
    cheat_ok = [c for c in cheats if apply_ips.bid_matches(c.rsplit('/', 1)[-1][:-4], title.main_bid())]
    has_other = any_files(os.path.join(d, 'romfs')) or any_files(os.path.join(d, 'romfs_ext')) or any_files(os.path.join(d, 'exefs'))
    main16 = title.main_bid()[:16]
    if patch_files and not matched and not has_other and not cheat_ok:
        problems.append('It was made for another version of the game: its code patches are for build %s, and this game\'s main is build %s.'
                        % (', '.join(sorted(others)), main16))
    elif others and patch_files:
        warnings.append('%d of its code patches are for other versions of the game (build %s) and are not used.'
                        % (len(patch_files) - len(matched), ', '.join(sorted(others))))
    if cheats and not cheat_ok:
        if not (patch_files or has_other):
            problems.append('Its cheats are for another version of the game (build %s); this game\'s main is build %s.'
                            % (', '.join(sorted(c.rsplit('/', 1)[-1][:-4] for c in cheats)), main16))
        else:
            warnings.append('Its cheats are for another version of the game and are not used.')
    for rel in walk_rel(os.path.join(d, 'exefs')):
        p = os.path.join(d, 'exefs', rel)
        if rel.endswith('.stub'):
            continue
        with open(p, 'rb') as f:
            magic = f.read(4)
        if rel == 'main.npdm' and magic != b'META' or rel != 'main.npdm' and magic != b'NSO0':
            problems.append('Its exefs/%s is not a %s.' % (rel, 'main.npdm' if rel == 'main.npdm' else 'code module (NSO)'))
    nro_patches = list(walk_rel(os.path.join(d, 'nro_patches')))
    if nro_patches:
        nro_bids = [b for _r, b, _s in title.nros()]
        for rel in walk_rel(os.path.join(d, 'romfs')):
            if rel.lower().endswith('.nro'):
                info = nro_info(os.path.join(d, 'romfs', *rel.split('/')))
                if info:
                    nro_bids.append(info[0])
        hit = [r for r in nro_patches if any(apply_ips.bid_matches(apply_ips.patch_build_id(os.path.join(d, 'nro_patches', *r.split('/'))), b)
                                             for b in nro_bids)]
        if not hit and not (patch_files or has_other or cheats):
            problems.append('Its NRO patches name no NRO of this version of the game (build %s).' % ', '.join(sorted(
                {(apply_ips.patch_build_id(os.path.join(d, 'nro_patches', *r.split('/'))) or r)[:16] for r in nro_patches})))
        elif len(hit) < len(nro_patches):
            warnings.append('%d of its NRO patches name no NRO of this game and are not used.' % (len(nro_patches) - len(hit)))
    fr, fr_errors = frame_rate_of(d)
    if fr is not None:
        if fr_errors:
            problems.append('Its frame_rate.ini has mistakes: %s.' % '; '.join(fr_errors[:5]))
        elif fr['build'] and not apply_ips.bid_matches(fr['build'], title.main_bid()):
            if not (patch_files or has_other or cheats):
                problems.append("Its frame-rate settings are for another version of the game (build %s); this game's main is build %s."
                                % (fr['build'][:16], main16))
            else:
                warnings.append('Its frame-rate settings are for another version of the game (build %s) and are not used.' % fr['build'][:16])
        else:
            for hk in fr['hooks']:
                mod_name, off, word = hook_site(hk)
                have = module_word(title, mod_name, off)
                if have is None:
                    problems.append('Its frame-step hook names %s+0x%x, which this game does not have.' % (mod_name, off))
                elif word and have != word:
                    problems.append('Its frame-step hook at %s+0x%x expects the instruction %s; this game has %s there.' % (mod_name, off, word, have))
            if fr['present_interval'] is None and not fr['fields'] and not fr['ue_fps_cvar'] and not fr['hooks']:
                warnings.append('Its frame_rate.ini sets nothing.')
    pokomac_checks(title, d, problems, warnings, patch_files, has_other, cheats)
    return problems, warnings, matched


def pokomac_checks(title, d, problems, warnings, patch_files, has_other, cheats):
    """What PokoMac's build and runtime cannot use (FRAME_RATE, NRO, the game's own modules): refused with the reason, or a warning when
    the rest of the mod still works."""
    for rel in walk_rel(os.path.join(d, 'exefs')):
        name = rel[:-5] if rel.endswith('.stub') else rel
        if rel == 'main.npdm':
            problems.append("Its exefs/main.npdm would replace the game's program settings, which PokoMac does not take from a mod.")
        elif rel.endswith('.stub'):
            problems.append('It removes the code module %s, and PokoMac always builds the game with all of its modules.' % name)
        elif name not in title.modules:
            problems.append("It adds the code module %s (a plugin loader or a new module): PokoMac builds only the game's own modules "
                            '(%s).' % (name, ', '.join(sorted(title.modules))))
        else:
            bid = nso_build_id(os.path.join(d, 'exefs', rel))
            if bid and not apply_ips.bid_matches(bid[:16], title.modules[name]):
                problems.append("Its exefs/%s is build %s, made for another version of the game (this game's %s is build %s)."
                                % (name, bid[:16], name, title.modules[name][:16]))
    nro_files = [r for r in walk_rel(os.path.join(d, 'romfs')) if r.lower().endswith('.nro')]
    if not NRO and (nro_files or any_files(os.path.join(d, 'nro_patches'))):
        problems.append('It brings NRO plugins or NRO patches%s. Pokopia loads no NRO, so PokoMac cannot use them.'
                        % (' (%s)' % ', '.join(nro_files[:3]) if nro_files else ''))
    if not FRAME_RATE and os.path.isfile(os.path.join(d, 'frame_rate', FRAME_RATE_INI)):
        if patch_files or has_other or cheats:
            warnings.append('Its frame_rate.ini is not used: PokoMac has no frame-rate engine (its code patches and game files are).')
        else:
            problems.append('It is a frame-rate mod (frame_rate.ini only), and PokoMac has no frame-rate engine: it would change nothing.')


def install(title, store, src, name=None, enabled=True):
    os.makedirs(store.dir, exist_ok=True)
    scratch = os.path.join(store.dir, '.unpack')
    source = open_source(src, scratch)
    results, refused = [], []
    try:
        fallback = os.path.splitext(os.path.basename(os.path.normpath(src)))[0] or 'mod'
        groups = detect(source.entries, title, fallback)
        for g in groups:
            label = name if (name and len(groups) == 1) else g['name']
            if g['title_id'] and not title.owns(g['title_id']):
                refused.append({'name': label, 'reason': 'It is a mod for another game (title %s); this game is %s.'
                                % (g['title_id'], title.title_id)})
                continue
            meta = {}
            if g['meta'].get('_member'):
                try:
                    meta = json.loads(source.read(g['meta']['_member']).decode('utf-8'))
                except (ValueError, KeyError, UnicodeDecodeError):
                    meta = {}
                if isinstance(meta, dict) and meta.get('title_id') and TID.match(str(meta['title_id'])) and not title.owns(meta['title_id']):
                    refused.append({'name': label, 'reason': 'It is a mod for another game (title %s); this game is %s.'
                                    % (str(meta['title_id']).upper(), title.title_id)})
                    continue
                if isinstance(meta, dict) and meta.get('name') and not name:
                    label = str(meta['name'])
            mid = store.new_id(label)
            staging = os.path.join(store.dir, '.staging-' + mid)
            rmtree(staging)
            wanted = {member: os.path.join(staging, cat, *rel.split('/')) for cat, rel, member in g['files']}
            source.extract(wanted)
            unpack_containers(staging)
            # romfs/<path>.stub: a deletion where the game has <path> (yuzu forks); otherwise an ordinary file of that name
            romfs_paths = None
            for cat, rel, _m in g['files']:
                if cat == 'romfs' and rel.lower().endswith('.stub'):
                    romfs_paths = romfs_paths if romfs_paths is not None else title.romfs_paths()
                    if rel[:-5] in romfs_paths:
                        dst = os.path.join(staging, 'romfs_ext', *rel.split('/'))
                        os.makedirs(os.path.dirname(dst), exist_ok=True)
                        os.replace(os.path.join(staging, 'romfs', *rel.split('/')), dst)
            problems, warnings, _ = check_mod(title, staging)
            if problems:
                rmtree(staging)
                refused.append({'name': label, 'reason': ' '.join(problems)})
                continue
            if not any_files(staging):
                rmtree(staging)
                refused.append({'name': label, 'reason': 'It holds no file this game can use.'})
                continue
            info = {'id': mid, 'name': label, 'enabled': bool(enabled), 'source': os.path.basename(os.path.normpath(src)),
                    'installed': time.strftime('%Y-%m-%d %H:%M:%S'), 'title_id': g['title_id'] or title.title_id,
                    'version': str(meta.get('version', '')) if isinstance(meta, dict) else '',
                    'author': str(meta.get('author', '')) if isinstance(meta, dict) else '',
                    'kinds': mod_kinds(staging), 'warnings': warnings, 'ignored': g['ignored'][:50]}
            write_json(os.path.join(staging, 'mod.json'), {k: info[k] for k in ('name', 'title_id', 'version', 'author', 'source')})
            os.replace(staging, store.mod_dir(mid))
            store.state['mods'].insert(0, info)       # a new mod goes on top: it wins over the ones before it
            results.append(info)
    finally:
        source.close()
        rmtree(scratch)
    if not results:
        reasons = '; '.join('%s: %s' % (r['name'], r['reason']) for r in refused) if refused else 'nothing to install'
        raise ModError('Not installed. ' + reasons)
    store.save()
    state = resolve(title, store)
    return {'installed': results, 'refused': refused, 'state': state}


