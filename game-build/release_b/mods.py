def ini_read(path):
    out, sec = {}, ''
    try:
        with open(path, 'r', encoding='utf-8-sig') as f:
            lines = f.read().splitlines()
    except OSError:
        return out
    for line in lines:
        s = line.strip()
        if not s or s[0] in ';#':
            continue
        if s.startswith('[') and s.endswith(']'):
            sec = s[1:-1].strip().lower()
            continue
        if '=' in s:
            k, v = s.split('=', 1)
            out[(sec, k.strip().lower())] = v.strip()
    return out


def ini_set(path, section, key, value):
    """Set (value a string) or remove (value None) one key of one section, keeping every other line."""
    try:
        with open(path, 'r', encoding='utf-8-sig') as f:
            lines = f.read().splitlines()
    except OSError:
        lines = []
    sec, start, end, at = '', None, None, None
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith('[') and s.endswith(']'):
            if sec == section and end is None:
                end = i
            sec = s[1:-1].strip().lower()
            if sec == section and start is None:
                start = i
            continue
        if sec == section and '=' in s and s[0] not in ';#' and s.split('=', 1)[0].strip().lower() == key:
            at = i
    if start is not None and end is None:
        end = len(lines)
    if at is not None:
        if value is None:
            del lines[at]
        else:
            lines[at] = '%s = %s' % (key, value)
    elif value is not None:
        if start is None:
            if lines and lines[-1].strip():
                lines.append('')
            lines += ['[%s]' % section, '%s = %s' % (key, value)]
        else:
            ins = end
            while ins > start + 1 and not lines[ins - 1].strip():
                ins -= 1
            lines.insert(ins, '%s = %s' % (key, value))
    else:
        return
    write_text(path, '\n'.join(lines) + '\n')


# ---------------------------------------------------------------- the title

def nso_build_id(path):
    """The NSO's ModuleId (header +0x40, 32 bytes) as 64 hex digits, '' when not an NSO."""
    try:
        with open(path, 'rb') as f:
            h = f.read(0x60)
    except OSError:
        return ''
    return h[0x40:0x60].hex() if h[:4] == b'NSO0' and len(h) >= 0x60 else ''


def npdm_program_id(path):
    try:
        with open(path, 'rb') as f:
            d = f.read()
    except OSError:
        return None
    if d[:4] != b'META' or len(d) < 0x80:
        return None
    aci = struct.unpack_from('<I', d, 0x70)[0]
    if d[aci:aci + 4] != b'ACI0':
        return None
    return struct.unpack_from('<Q', d, aci + 0x10)[0]


class Title:
    """A title folder of the library: its pkp.ini [fs] exefs / romfs / romfs_base, program id and module build ids."""

    def __init__(self, folder):
        self.dir = os.path.abspath(folder)
        if not os.path.isdir(self.dir):
            raise ModError('No title folder %s.' % self.dir)
        self.ini_path = os.path.join(self.dir, 'pkp.ini')
        ini = ini_read(self.ini_path)
        rel = lambda v: v if not v or os.path.isabs(v) else os.path.join(self.dir, v)
        self.exefs = rel(ini.get(('fs', 'exefs'), 'exefs'))
        self.romfs = rel(ini.get(('fs', 'romfs'), 'romfs'))
        self.romfs_base = rel(ini.get(('fs', 'romfs_base'), ''))
        self.ini = ini
        if not os.path.isdir(self.exefs):
            raise ModError("The title's game files are not where its settings say (%s)." % self.exefs)
        self.modules = {}
        for n in NSO_NAMES:
            bid = nso_build_id(os.path.join(self.exefs, n))
            if bid:
                self.modules[n] = bid
        if 'main' not in self.modules:
            raise ModError('The title has no main module in %s.' % self.exefs)
        pid = npdm_program_id(os.path.join(self.exefs, 'main.npdm'))
        self.program_id = pid
        ids = set()
        if pid is not None:
            ids.add(pid & ~0xFFF)
        base = os.path.basename(self.dir)
        if TID.match(base):
            ids.add(int(base, 16) & ~0xFFF)
        self.ids = ids
        self._romfs_paths = None

    def owns(self, tid_hex):
        """Whether a title id from a mod's path is this title's (its base game or update; an add-on has its own id)."""
        return (int(tid_hex, 16) & ~0xFFF) in self.ids

    @property
    def title_id(self):
        return '%016X' % self.program_id if self.program_id is not None else os.path.basename(self.dir).upper()

    def main_bid(self):
        return self.modules['main']

    def view(self):
        """The game's RomFS through the one reader every scanner uses (tools/intake/romfs_view.py, coord/ROMFS_VIEW.md): a folder, a
        .nup or a romfs.nxsrc (an .nsp / .xci title read in place from the owner's package), the update's files over the base's.
        None when the reader is not there (an older package) or the title has no RomFS: the folder and .nup readers below stand in."""
        if getattr(self, '_view', None) is None:
            self._view = False
            rv = _romfs_view()
            if rv and self.romfs and os.path.exists(self.romfs):
                base = self.romfs_base if self.romfs_base and os.path.exists(self.romfs_base) else None
                try:
                    self._view = rv.open_view(self.romfs, base)
                except Exception as e:      # a source the reader cannot open: said, and the older readers try
                    sys.stderr.write('mods: the RomFS reader cannot open %s (%s)\n' % (self.romfs, e))
        return self._view or None

    def romfs_paths(self):
        """Every file path of the game's RomFS (POSIX, no leading slash), the update's over the base's."""
        if self._romfs_paths is None:
            v = self.view()
            if v:
                self._romfs_paths = {p for p, _size in v.files()}
                return self._romfs_paths
            paths = set()
            for src in (self.romfs_base, self.romfs):
                if not src:
                    continue
                if os.path.isdir(src):
                    for root, _dirs, files in os.walk(src):
                        for n in files:
                            paths.add(fwd(os.path.relpath(os.path.join(root, n), src)))
                elif os.path.isfile(src):
                    paths |= set(nup_romfs(src))
            self._romfs_paths = paths
        return self._romfs_paths

    def nros(self):
        """The game's NROs (a RomFS file with an NRO header): [(path in the RomFS, its build id as 64 hex digits, SHA-256 hex)]."""
        if getattr(self, '_nros', None) is None:
            out = {}
            v = self.view()
            if v:
                for rel, size in v.files():
                    if rel.lower().endswith('.nro') and size >= 0x80:
                        head = v.read(rel, 0, 0x80)
                        if head[0x10:0x14] == b'NRO0' and struct.unpack_from('<I', head, 0x18)[0] == size:
                            info = nro_info_bytes(v.read(rel))
                            if info:
                                out[rel] = info
            else:
                for src in (self.romfs_base, self.romfs):
                    if not src:
                        continue
                    if os.path.isdir(src):
                        for root, _dirs, files in os.walk(src):
                            for n in files:
                                if n.lower().endswith('.nro'):
                                    full = os.path.join(root, n)
                                    info = nro_info(full)
                                    if info:
                                        out[fwd(os.path.relpath(full, src))] = info
                    elif os.path.isfile(src):
                        out.update(nup_nros(src))
            self._nros = [(rel, bid, sha) for rel, (bid, sha) in sorted(out.items())]
        return self._nros

    def nro_bytes(self, rel):
        """The game's NRO at RomFS path `rel` (the update's, else the base's), or None."""
        v = self.view()
        if v:
            return v.read(rel) if v.isfile(rel) else None
        for src in (self.romfs, self.romfs_base):
            if src and os.path.isdir(src):
                p = os.path.join(src, *rel.split('/'))
                if os.path.isfile(p):
                    with open(p, 'rb') as f:
                        return f.read()
            elif src and os.path.isfile(src):
                import tempfile
                with tempfile.TemporaryDirectory() as t:
                    dst = os.path.join(t, 'x.nro')
                    if nup_extract(src, rel, dst):
                        with open(dst, 'rb') as f:
                            return f.read()
        return None

    def romfs_top(self):
        return {p.split('/')[0] for p in self.romfs_paths()}

    def romfs_local(self, rel):
        """A real path of the game's RomFS file `rel` when it is one (a folder's file), else None (inside a .nup or a package)."""
        v = self.view()
        if v:
            return v.local_path(rel) if v.isfile(rel) else None
        for src in (self.romfs, self.romfs_base):
            if src and os.path.isdir(src) and os.path.isfile(os.path.join(src, *rel.split('/'))):
                return os.path.join(src, *rel.split('/'))
        return None

    def romfs_file(self, rel, dest):
        """Write the game's RomFS file `rel` to dest (the update's, else the base's). False when the game has none."""
        v = self.view()
        if v:
            if not v.isfile(rel):
                return False
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with v.open(rel) as src, open(dest, 'wb') as out:
                shutil.copyfileobj(src, out, 1 << 20)
            return True
        for src in (self.romfs, self.romfs_base):
            if not src:
                continue
            if os.path.isdir(src):
                p = os.path.join(src, *rel.split('/'))
                if os.path.isfile(p):
                    os.makedirs(os.path.dirname(dest), exist_ok=True)
                    shutil.copyfile(p, dest)
                    return True
            elif os.path.isfile(src):
                if nup_extract(src, rel, dest):
                    return True
        return False


def nro_info(path):
    """(build id as 64 hex digits, SHA-256 hex) of an NRO file (its header's size matches the file), or None."""
    try:
        with open(path, 'rb') as f:
            data = f.read()
    except OSError:
        return None
    return nro_info_bytes(data)


def nro_info_bytes(data):
    if len(data) < 0x80 or data[0x10:0x14] != b'NRO0' or struct.unpack_from('<I', data, 0x18)[0] != len(data):
        return None
    return data[0x40:0x60].hex(), hashlib.sha256(data).hexdigest()


def nup_nros(path):
    n, files = _nup_romfs_index(path)
    out = {}
    if not n:
        return out
    import tempfile
    try:
        with tempfile.TemporaryDirectory() as t:
            for rel, fi in files.items():
                if rel.lower().endswith('.nro'):
                    dst = os.path.join(t, 'x.nro')
                    try:
                        n.extract_file(fi, dst)
                    except Exception:
                        continue
                    info = nro_info(dst)
                    if info:
                        out[rel] = info
    finally:
        n.close()
    return out


def _romfs_view():
    """The RomFS reader tools/intake/romfs_view.py, run as a program of its own through tools/intake/romfs_client.py (open_view, the same
    views; the intake is never imported here: coord license_inventory.md, group A), beside the build tools in a package (tools/intake) or
    in the repository; None when absent."""
    for d in (os.path.join(os.path.dirname(HERE), 'intake'), os.path.join(HERE, '..', '..', 'tools', 'intake')):
        if os.path.isfile(os.path.join(d, 'romfs_client.py')):
            d = os.path.abspath(d)
            if d not in sys.path:
                sys.path.insert(0, d)
            try:
                import romfs_client
                return romfs_client if romfs_client.available() else None
            except Exception:
                return None
    return None


def _nupread():
    for d in (os.path.join(os.path.dirname(HERE), 'intake'), os.path.join(HERE, 'macos', 'intake'), os.path.join(HERE, 'intake')):
        if os.path.isfile(os.path.join(d, 'nupread.py')):
            if d not in sys.path:
                sys.path.insert(0, d)
            import nupread
            return nupread
    return None


def _nup_romfs_index(path):
    nr = _nupread()
    if not nr:
        return None, {}
    n = nr.Nup(path)
    files = {}
    for pkg in n.packages:
        if pkg['romfs'] is not None and pkg['kind'] in ('base', 'update', 'program', 'patch', '0', '1'):
            for rel, fi in n.walk(pkg['romfs']):
                files[rel] = fi
    if not files:
        for pkg in n.packages:
            if pkg['romfs'] is not None:
                for rel, fi in n.walk(pkg['romfs']):
                    files.setdefault(rel, fi)
                break
    return n, files


def nup_romfs(path):
    n, files = _nup_romfs_index(path)
    if n:
        n.close()
    return list(files)


def nup_extract(path, rel, dest):
    n, files = _nup_romfs_index(path)
    if not n:
        return False
    try:
        if rel not in files:
            return False
        n.extract_file(files[rel], dest)
        return True
    finally:
        n.close()


