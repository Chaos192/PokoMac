def export(title, out, romfs=False, romfs_path='', exefs=True):
    """A modder's start: the title's identity and build ids (info.json), its code modules uncompressed (an offset in them is the offset a
    code patch uses), and the RomFS tree or a part of it (hardlinks where the volume allows, else copies)."""
    root = os.path.join(os.path.abspath(out), title.title_id)
    os.makedirs(root, exist_ok=True)
    info = {'title_id': title.title_id, 'modules': {n: {'build_id': b, 'patch_name': b[:16]} for n, b in sorted(title.modules.items())},
            'patch_offsets': 'An offset in exefs/<module> here is the offset an IPS/IPS32 patch uses (0x100 + the mapped offset); '
                             'in a .pchtxt with "@flag offset_shift 0x100" use the mapped offset (this offset - 0x100).'}
    info['nros'] = {rel: {'build_id': bid, 'patch_name': bid[:16]} for rel, bid, _sha in title.nros()}   # nro_patches name these
    write_json(os.path.join(root, 'info.json'), info)
    n_ex = n_rom = 0
    if exefs:
        for n in title.modules:
            data = open(os.path.join(title.exefs, n), 'rb').read()
            header, segs, _ = apply_ips.decompress_nso(data)
            img = apply_ips.build_uncompressed_nso(header, segs)
            os.makedirs(os.path.join(root, 'exefs'), exist_ok=True)
            with open(os.path.join(root, 'exefs', n), 'wb') as f:
                f.write(img)
            n_ex += 1
        if os.path.isfile(os.path.join(title.exefs, 'main.npdm')):
            shutil.copyfile(os.path.join(title.exefs, 'main.npdm'), os.path.join(root, 'exefs', 'main.npdm'))
    if romfs:
        prefix = fwd(romfs_path).strip('/')
        for rel in sorted(title.romfs_paths()):
            if prefix and not (rel == prefix or rel.startswith(prefix + '/')):
                continue
            dst = os.path.join(root, 'romfs', *rel.split('/'))
            local = title.romfs_local(rel)
            if local:
                link_or_copy(local, dst)          # a folder's file: a hardlink where the volume allows
            else:
                title.romfs_file(rel, dst)        # inside a .nup or a package: its bytes, read in place
            n_rom += 1
    return {'out': fwd(root), 'modules': n_ex, 'romfs_files': n_rom, 'info': info}


def template(title, out, name):
    d = os.path.join(os.path.abspath(out), name)
    if os.path.exists(d):
        raise ModError('%s is already there.' % d)
    main = title.main_bid()
    for sub in ('romfs', 'exefs', 'cheats'):
        os.makedirs(os.path.join(d, sub))
    write_json(os.path.join(d, 'mod.json'), {'name': name, 'title_id': title.title_id, 'version': '1.0', 'author': ''})
    write_text(os.path.join(d, 'romfs', 'README.txt'),
               "Put files here at the same path the game's RomFS has them (for example Model/Player.bfres). They replace the game's.\n"
               "To remove a game file, put an empty file named <its path>.stub in a folder romfs_ext beside this one.\n")
    write_text(os.path.join(d, 'exefs', main[:16] + '.pchtxt.example'),
               '@nsobid-%s\n\n# A code patch for main (rename to .pchtxt to use it). Offsets are mapped offsets in main (text at 0).\n'
               '@flag offset_shift 0x100\n\n@disabled\n// 00123456 1F2003D5    // NOP the instruction at main+0x123456\n\n@stop\n' % main)
    write_text(os.path.join(d, 'cheats', main[:16] + '.txt.example'),
               '[Example cheat]\n// 04000000 00123456 0000270F   // write 9999 to main+0x123456 (Atmosphere cheat format)\n')
    return {'out': fwd(d), 'build_id': main[:16]}


def pack(folder, out):
    folder = os.path.abspath(folder)
    name = os.path.basename(folder)
    n = 0
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
        for rel in walk_rel(folder):
            if rel.endswith('.example') or rel.rsplit('/', 1)[-1] == 'README.txt':
                continue
            z.write(os.path.join(folder, *rel.split('/')), name + '/' + rel)
            n += 1
    return {'out': fwd(os.path.abspath(out)), 'files': n}


# ---------------------------------------------------------------- command line

def main(argv=None):
    ap = argparse.ArgumentParser(prog='mods.py', description='PokoMac mod manager (docs/MODS.md)')
    ap.add_argument('command', choices=('scan', 'install', 'list', 'enable', 'disable', 'move', 'uninstall', 'resolve', 'built',
                                        'export', 'template', 'pack'))
    ap.add_argument('args', nargs='*')
    ap.add_argument('--title')
    ap.add_argument('--store')
    ap.add_argument('--no-ini', action='store_true')
    ap.add_argument('--name')
    ap.add_argument('--disabled', action='store_true')
    ap.add_argument('--out')
    ap.add_argument('--romfs', action='store_true')
    ap.add_argument('--romfs-path', default='')
    ap.add_argument('--no-exefs', action='store_true')
    a = ap.parse_args(argv)
    try:
        c, args = a.command, a.args
        if c == 'pack':
            say_json(pack(args[0], a.out or (os.path.abspath(args[0]) + '.zip')))
            return 0
        if c == 'scan':
            title = Title(a.title) if a.title else None
            import tempfile
            src = open_source(args[0], os.path.join(tempfile.mkdtemp(prefix='anyswitch-mods-'), 'unpack'))
            try:
                groups = detect(src.entries, title, os.path.splitext(os.path.basename(os.path.normpath(args[0])))[0])
            finally:
                src.close()
            say_json({'mods': [{'name': g['name'], 'title_id': g['title_id'], 'files': len(g['files']),
                                'kinds': sorted({f[0] for f in g['files']}), 'ignored': g['ignored'][:20]} for g in groups]})
            return 0
        if not args:
            raise ModError('Name the title folder.')
        title = Title(args[0])
        store = Store(title, a.store, not a.no_ini)
        if c == 'install':
            say_json(install(title, store, args[1], a.name, not a.disabled))
        elif c == 'list':
            say_json(status(title, store))
        elif c in ('enable', 'disable'):
            store.find(args[1])['enabled'] = c == 'enable'
            store.save()
            say_json(resolve(title, store))
        elif c == 'move':
            m = store.find(args[1])
            store.state['mods'].remove(m)
            store.state['mods'].insert(max(0, min(int(args[2]), len(store.state['mods']))), m)
            store.save()
            say_json(resolve(title, store))
        elif c == 'uninstall':
            m = store.find(args[1])
            store.state['mods'].remove(m)
            store.save()
            rmtree(store.mod_dir(m['id']))
            say_json(resolve(title, store))
        elif c == 'resolve':
            say_json(resolve(title, store))
        elif c == 'built':
            say_json(built(title, store))
        elif c == 'export':
            say_json(export(title, a.out or os.path.join(title.dir, 'mods-export'), a.romfs, a.romfs_path, not a.no_exefs))
        elif c == 'template':
            say_json(template(title, a.out or os.path.join(title.dir, 'mods-make'), a.name or 'My mod'))
        return 0
    except (ModError, apply_ips.IpsError) as e:
        say_json({'error': str(e)})
        return 1


if __name__ == '__main__':
    sys.exit(main())
