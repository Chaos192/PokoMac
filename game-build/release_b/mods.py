class FolderSource:
    def __init__(self, path):
        self.path = os.path.abspath(path)
        self.entries = {}
        for root, dirs, files in os.walk(self.path):
            dirs.sort()
            for n in sorted(files):
                full = os.path.join(root, n)
                self.entries[fwd(os.path.relpath(full, self.path))] = os.path.getsize(full)

    def read(self, rel):
        with open(os.path.join(self.path, *rel.split('/')), 'rb') as f:
            return f.read()

    def extract(self, wanted):
        for rel, dest in wanted.items():
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            shutil.copyfile(os.path.join(self.path, *rel.split('/')), dest)

    def close(self):
        pass


class ZipSource:
    def __init__(self, path):
        try:
            self.z = zipfile.ZipFile(path)
        except zipfile.BadZipFile as e:
            raise ModError('%s is not a zip file that can be read (%s).' % (os.path.basename(path), e))
        self.entries, self.names = {}, {}
        for info in self.z.infolist():
            if info.is_dir():
                continue
            if info.flag_bits & 1:
                raise ModError('%s is password protected: unpack it first, then install the folder.' % os.path.basename(path))
            rel = safe_rel(info.filename)
            if rel is None:
                raise ModError('%s holds a file outside its own folder (%s): not installed.' % (os.path.basename(path), info.filename))
            if rel:
                self.entries[rel] = info.file_size
                self.names[rel] = info

    def read(self, rel):
        return self.z.read(self.names[rel])

    def extract(self, wanted):
        for rel, dest in wanted.items():
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with self.z.open(self.names[rel]) as src, open(dest, 'wb') as out:
                shutil.copyfileobj(src, out, 1 << 20)

    def close(self):
        self.z.close()


class _Buf:
    def __init__(self, data):
        self.d, self.i = data, 0

    def byte(self):
        if self.i >= len(self.d):
            raise ModError('the 7z header ends early')
        b = self.d[self.i]
        self.i += 1
        return b

    def take(self, n):
        if self.i + n > len(self.d):
            raise ModError('the 7z header ends early')
        b = self.d[self.i:self.i + n]
        self.i += n
        return b

    def u32(self):
        return struct.unpack('<I', self.take(4))[0]

    def num(self):
        first = self.byte()
        mask, value = 0x80, 0
        for i in range(8):
            if not first & mask:
                return value | ((first & (mask - 1)) << (8 * i))
            value |= self.byte() << (8 * i)
            mask >>= 1
        return value

    def bits(self, n):
        out, b, mask = [], 0, 0
        for _ in range(n):
            if not mask:
                b, mask = self.byte(), 0x80
            out.append(bool(b & mask))
            mask >>= 1
        return out

    def digests(self, n):
        defined = [True] * n if self.byte() else self.bits(n)
        return [self.u32() if d else None for d in defined]


class SevenZip:
    """A 7z archive read with the standard library: LZMA, LZMA2, Copy, Deflate, BZip2 and the BCJ / Delta filters. Written from the 7z
    format's documentation (7zFormat.txt of the LZMA SDK, public domain); no 7-Zip code."""
    SIG = b'7z\xbc\xaf\x27\x1c'

    def __init__(self, path):
        self.path = path
        self.f = open(path, 'rb')
        h = self.f.read(32)
        if h[:6] != self.SIG:
            raise ModError('%s is not a 7z archive.' % os.path.basename(path))
        off, size, crc = struct.unpack_from('<QQI', h, 12)
        self.f.seek(32 + off)
        data = self.f.read(size)
        if len(data) != size or zlib.crc32(data) != crc:
            raise ModError('%s is damaged (its header does not match its checksum).' % os.path.basename(path))
        b = _Buf(data)
        t = b.byte() if size else 0x01
        self.si, self.files = None, []
        if not size:
            return
        while t == 0x17:      # an encoded header: the real one is packed like a file
            si = self._streams(b)
            data = self._read_folder(si, 0)
            b = _Buf(data)
            t = b.byte()
        if t != 0x01:
            raise ModError('%s: a 7z header this reader does not know (0x%02x).' % (os.path.basename(path), t))
        self._header(b)

    # -- header
    def _header(self, b):
        while True:
            t = b.byte()
            if t == 0x00:
                break
            if t == 0x02:         # archive properties
                while True:
                    if b.byte() == 0:
                        break
                    b.take(b.num())
            elif t == 0x03:
                self._streams(b)
            elif t == 0x04:
                self.si = self._streams(b)
            elif t == 0x05:
                self._files(b)
            else:
                raise ModError('7z: unknown header field 0x%02x' % t)

    def _folder(self, b):
        coders, n_in, n_out = [], 0, 0
        for _ in range(b.num()):
            flag = b.byte()
            cid = bytes(b.take(flag & 0x0F))
            ni, no = (b.num(), b.num()) if flag & 0x10 else (1, 1)
            props = bytes(b.take(b.num())) if flag & 0x20 else b''
            if flag & 0x80:
                raise ModError('7z: alternative coder methods are not supported')
            coders.append({'id': cid, 'in': ni, 'out': no, 'props': props})
            n_in += ni
            n_out += no
        binds = [(b.num(), b.num()) for _ in range(n_out - 1)]
        n_packed = n_in - len(binds)
        if n_packed == 1:
            bound = {i for i, _ in binds}
            packed = [next(i for i in range(n_in) if i not in bound)]
        else:
            packed = [b.num() for _ in range(n_packed)]
        return {'coders': coders, 'binds': binds, 'packed': packed, 'n_out': n_out}

    def _streams(self, b):
        si = {'pack_pos': 0, 'pack_sizes': [], 'folders': [], 'sub': None}
        while True:
            t = b.byte()
            if t == 0x00:
                break
            if t == 0x06:
                si['pack_pos'] = b.num()
                n = b.num()
                while True:
                    t2 = b.byte()
                    if t2 == 0x00:
                        break
                    if t2 == 0x09:
                        si['pack_sizes'] = [b.num() for _ in range(n)]
                    elif t2 == 0x0A:
                        b.digests(n)
                    else:
                        raise ModError('7z: unknown pack info field 0x%02x' % t2)
            elif t == 0x07:
                if b.byte() != 0x0B:
                    raise ModError('7z: no folder list')
                nf = b.num()
                if b.byte() != 0:
                    raise ModError('7z: external folder lists are not supported')
                si['folders'] = [self._folder(b) for _ in range(nf)]
                if b.byte() != 0x0C:
                    raise ModError('7z: no unpack sizes')
                for fo in si['folders']:
                    fo['sizes'] = [b.num() for _ in range(fo['n_out'])]
                    bound_out = {o for _, o in fo['binds']}
                    fo['size'] = fo['sizes'][next(i for i in range(fo['n_out']) if i not in bound_out)]
                    fo['crc'] = None
                while True:
                    t2 = b.byte()
                    if t2 == 0x00:
                        break
                    if t2 == 0x0A:
                        for fo, c in zip(si['folders'], b.digests(nf)):
                            fo['crc'] = c
                    else:
                        raise ModError('7z: unknown unpack info field 0x%02x' % t2)
            elif t == 0x08:
                folders = si['folders']
                counts = [1] * len(folders)
                t2 = b.byte()
                if t2 == 0x0D:
                    counts = [b.num() for _ in folders]
                    t2 = b.byte()
                sizes = []
                for fo, c in zip(folders, counts):
                    if not c:
                        sizes.append([])
                        continue
                    if t2 == 0x09:
                        part = [b.num() for _ in range(c - 1)]
                        sizes.append(part + [fo['size'] - sum(part)])
                    else:
                        sizes.append([fo['size']])
                if t2 == 0x09:
                    t2 = b.byte()
                crcs = [[None] * c for c in counts]
                for k, (fo, c) in enumerate(zip(folders, counts)):
                    if c == 1 and fo['crc'] is not None:
                        crcs[k] = [fo['crc']]
                while t2 != 0x00:
                    if t2 == 0x0A:
                        want = [(k, j) for k, (fo, c) in enumerate(zip(folders, counts)) for j in range(c)
                                if not (c == 1 and fo['crc'] is not None)]
                        for (k, j), d in zip(want, b.digests(len(want))):
                            crcs[k][j] = d
                    else:
                        b.take(b.num())
                    t2 = b.byte()
                si['sub'] = (counts, sizes, crcs)
            else:
                raise ModError('7z: unknown streams field 0x%02x' % t)
        if si['sub'] is None:
            si['sub'] = ([1] * len(si['folders']), [[fo['size']] for fo in si['folders']], [[fo['crc']] for fo in si['folders']])
        return si

    def _files(self, b):
        n = b.num()
        empty_stream, empty_file, anti, names = [False] * n, None, None, [''] * n
        while True:
            t = b.byte()
            if t == 0x00:
                break
            size = b.num()
            sub = _Buf(b.take(size))
            if t == 0x0E:
                empty_stream = sub.bits(n)
            elif t == 0x0F:
                empty_file = sub.bits(sum(empty_stream))
            elif t == 0x10:
                anti = sub.bits(sum(empty_stream))
            elif t == 0x11:
                if sub.byte() != 0:
                    raise ModError('7z: external file names are not supported')
                raw = bytes(sub.d[sub.i:])
                names = raw.decode('utf-16-le').split('\x00')[:n]
        counts, sizes, crcs = self.si['sub'] if self.si else ([], [], [])
        streams = [(k, j, sizes[k][j], crcs[k][j]) for k in range(len(counts)) for j in range(counts[k])]
        si = ei = 0
        for i in range(n):
            if not empty_stream[i]:
                k, j, sz, crc = streams[si]
                si += 1
                self.files.append({'name': names[i], 'folder': k, 'index': j, 'size': sz, 'crc': crc, 'dir': False})
            else:
                is_file = bool(empty_file and empty_file[ei])
                is_anti = bool(anti and anti[ei])
                ei += 1
                if not is_anti:
                    self.files.append({'name': names[i], 'folder': None, 'index': 0, 'size': 0, 'crc': None, 'dir': not is_file})

    # -- data
    def _pack_offset(self, si, folder_index):
        first = sum(len(si['folders'][k]['packed']) for k in range(folder_index))
        return 32 + si['pack_pos'] + sum(si['pack_sizes'][:first]), si['pack_sizes'][first]

    def _decoder(self, fo):
        """A decompressor for a linear chain of coders (each one in, one out): lzma filters, or Deflate / BZip2 / Copy alone."""
        if len(fo['packed']) != 1 or any(c['in'] != 1 or c['out'] != 1 for c in fo['coders']):
            raise ModError('7z: a coder with several streams (BCJ2) is not supported by the built-in reader')
        chain, out_index = [], next(i for i in range(fo['n_out']) if i not in {o for _, o in fo['binds']})
        k = out_index
        while True:
            chain.append(fo['coders'][k])
            bind = [i for i, o in fo['binds'] if i == k]
            if not bind:
                break
            k = dict(fo['binds'])[k]
        filters, other = [], None
        for c in chain:
            cid, p = c['id'], c['props']
            if cid == b'\x00':
                continue
            if cid == b'\x03\x01\x01':
                d = p[0]
                filters.append({'id': lzma.FILTER_LZMA1, 'dict_size': struct.unpack_from('<I', p, 1)[0],
                                'lc': d % 9, 'lp': (d // 9) % 5, 'pb': d // 45})
            elif cid == b'\x21':
                d = p[0]
                filters.append({'id': lzma.FILTER_LZMA2, 'dict_size': 0xFFFFFFFF if d >= 40 else (2 | (d & 1)) << (d // 2 + 11)})
            elif cid == b'\x03\x03\x01\x03':
                filters.append({'id': lzma.FILTER_X86})
            elif cid == b'\x03\x03\x05\x01':
                filters.append({'id': lzma.FILTER_ARM})
            elif cid == b'\x03\x03\x07\x01':
                filters.append({'id': lzma.FILTER_ARMTHUMB})
            elif cid == b'\x0a' and hasattr(lzma, 'FILTER_ARM64'):
                filters.append({'id': lzma.FILTER_ARM64})
            elif cid == b'\x03':
                filters.append({'id': lzma.FILTER_DELTA, 'dist': p[0] + 1})
            elif cid in (b'\x04\x01\x08', b'\x04\x02\x02') and len(chain) == 1:
                other = cid
            elif cid.startswith(b'\x06\xf1\x07'):
                raise ModError('the 7z archive is password protected: unpack it first, then install the folder')
            else:
                raise ModError('7z: compression method %s is not supported by the built-in reader' % cid.hex())
        if other == b'\x04\x01\x08':
            return 'zlib', zlib.decompressobj(-15)
        if other == b'\x04\x02\x02':
            return 'bz2', bz2.BZ2Decompressor()
        if not filters:
            return 'copy', None
        if filters[-1]['id'] not in (lzma.FILTER_LZMA1, lzma.FILTER_LZMA2):
            raise ModError('7z: a filter chain without LZMA is not supported by the built-in reader')
        return 'lzma', lzma.LZMADecompressor(format=lzma.FORMAT_RAW, filters=filters)

    def _stream(self, si, k):
        """Yield the folder's unpacked bytes in chunks."""
        fo = si['folders'][k]
        pos, left_in = self._pack_offset(si, k)
        kind, d = self._decoder(fo)
        left_out = fo['size']
        tail = b''
        while left_out > 0:
            if kind == 'copy':
                self.f.seek(pos)
                chunk = self.f.read(min(1 << 20, left_in, left_out))
                if not chunk:
                    raise ModError('7z: the archive ends early')
                pos += len(chunk)
                left_in -= len(chunk)
                out = chunk
            else:
                need = kind == 'zlib' and not tail or kind != 'zlib' and d.needs_input
                data = b''
                if need and left_in > 0:
                    self.f.seek(pos)
                    data = self.f.read(min(1 << 20, left_in))
                    pos += len(data)
                    left_in -= len(data)
                elif need:
                    if kind == 'zlib':
                        out = d.flush()[:left_out]
                        if not out:
                            raise ModError('7z: a packed stream ends early')
                        left_out -= len(out)
                        yield out
                        continue
                    raise ModError('7z: a packed stream ends early')
                if kind == 'zlib':
                    out = d.decompress(tail + data, min(left_out, 1 << 22))
                    tail = d.unconsumed_tail
                else:
                    if getattr(d, 'eof', False):
                        raise ModError('7z: a packed stream ends early')
                    out = d.decompress(data, min(left_out, 1 << 22))
            if out:
                left_out -= len(out)
                yield out

    def _read_folder(self, si, k):
        return b''.join(self._stream(si, k))

    def extract(self, wanted):
        """wanted: {member name: destination}. Each folder is decoded once, in order; the members not wanted are skipped over."""
        by_name = {safe_rel(f['name']): f for f in self.files}
        folders = {}
        for rel, dest in wanted.items():
            f = by_name[rel]
            if f['folder'] is None:
                os.makedirs(os.path.dirname(dest), exist_ok=True)
                open(dest, 'wb').close()
            else:
                folders.setdefault(f['folder'], {})[f['index']] = (f, dest)
        for k in sorted(folders):
            members = sorted((f['index'], f) for f in self.files if f['folder'] == k)
            want = folders[k]
            stream = self._stream(self.si, k)
            buf = b''
            for j, f in members:
                left = f['size']
                out, crc = None, 0
                if j in want:
                    dest = want[j][1]
                    os.makedirs(os.path.dirname(dest), exist_ok=True)
                    out = open(dest, 'wb')
                try:
                    while left > 0:
                        if not buf:
                            buf = next(stream, b'')
                            if not buf:
                                raise ModError('7z: %s ends early' % f['name'])
                        piece, buf = buf[:left], buf[left:]
                        left -= len(piece)
                        if out:
                            out.write(piece)
                            crc = zlib.crc32(piece, crc)
                finally:
                    if out:
                        out.close()
                if out and f['crc'] is not None and crc != f['crc']:
                    raise ModError('7z: %s does not match its checksum (the archive is damaged)' % f['name'])
                if len(want) == sum(1 for jj in want if jj <= j):
                    break

    def close(self):
        self.f.close()


class SevenZipSource:
    def __init__(self, path):
        self.z = SevenZip(path)
        self.entries = {}
        for f in self.z.files:
            if f['dir']:
                continue
            rel = safe_rel(f['name'])
            if rel is None:
                raise ModError('%s holds a file outside its own folder (%s): not installed.' % (os.path.basename(path), f['name']))
            if rel:
                self.entries[rel] = f['size']

    def read(self, rel):
        import tempfile
        with tempfile.TemporaryDirectory() as t:
            p = os.path.join(t, 'f')
            self.z.extract({rel: p})
            with open(p, 'rb') as f:
                return f.read()

    def extract(self, wanted):
        self.z.extract(wanted)

    def close(self):
        self.z.close()


def external_unpacker():
    for name in ('7zz', '7z', '7za'):
        p = shutil.which(name)
        if p:
            return [p, 'x', '-y', '-bd', '-o{out}', '{src}']
    for name in ('bsdtar', 'tar'):
        p = shutil.which(name)
        if p:
            return [p, '-xf', '{src}', '-C', '{out}']
    return None


def open_source(src, scratch):
    """A folder, .zip or .7z as a source; another archive (.rar, or a 7z method the built-in reader lacks) unpacked into `scratch` by a 7-Zip
    or bsdtar found on the PATH."""
    if os.path.isdir(src):
        return FolderSource(src)
    if not os.path.isfile(src):
        raise ModError('Nothing to install at %s.' % src)
    with open(src, 'rb') as f:
        magic = f.read(8)
    if magic[:4] == b'PK\x03\x04' or magic[:4] == b'PK\x05\x06':
        return ZipSource(src)
    if magic[:6] == SevenZip.SIG:
        try:
            return SevenZipSource(src)
        except ModError as e:
            if 'password' in str(e):
                raise
            first = e
    else:
        first = ModError('%s is not a zip, 7z or folder.' % os.path.basename(src))
    cmd = external_unpacker()
    if not cmd:
        raise ModError('%s Unpack it yourself, then install the folder.' % first)
    rmtree(scratch)
    os.makedirs(scratch)
    r = subprocess.run([a.replace('{out}', scratch).replace('{src}', os.path.abspath(src)) for a in cmd], stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT)
    if r.returncode != 0:
        raise ModError('%s could not be unpacked (%s).' % (os.path.basename(src), r.stdout.decode('utf-8', 'replace').strip()[-300:]))
    return FolderSource(scratch)


