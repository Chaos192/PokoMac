def classify(category, rel):
    """(category, rel) of one file inside a mod root: patches in exefs/ go to patches, cheat files are .txt, unknown files are None."""
    low = rel.lower()
    base = low.rsplit('/', 1)[-1]
    if category == 'exefs':
        if base.endswith(PATCH_EXTS):
            return 'patches', rel.rsplit('/', 1)[-1]
        if '/' not in rel and (base in EXEFS_NAMES or (base.endswith('.stub') and base[:-5] in EXEFS_NAMES)):
            return 'exefs', base
        return None
    if category == 'romfs_ext':
        return ('romfs_ext', rel) if base.endswith(('.stub', '.ips')) else None
    if category == 'cheats':
        return ('cheats', rel.rsplit('/', 1)[-1]) if base.endswith('.txt') else None
    if category in ('patches', 'nro_patches'):
        return (category, rel) if base.endswith(PATCH_EXTS) else None
    return category, rel


def detect(entries, title=None, fallback_name='mod'):
    """The mods a source holds: [{'name', 'title_id' (hex or None), 'files': [(category, rel, member)], 'ignored': [member], 'meta'}]."""
    groups, loose = {}, []
    for member in sorted(entries):
        segs = member.split('/')
        if segs[-1].lower() in JUNK or segs[0] == '__MACOSX' or segs[-1].startswith('._'):
            continue
        if segs[-1].lower() == FRAME_RATE_INI and not any(x.lower() in ANCHORS for x in segs[:-1]):   # a mod's frame-rate block
            root = segs[:-1]
            g = groups.setdefault(tuple(root), {'root': root, 'name_hint': None, 'files': [], 'ignored': []})
            g['files'].append(('frame_rate', FRAME_RATE_INI, member))
            continue
        if segs[-1].lower() in CONTAINERS:      # Ryujinx: <mod>/romfs.bin (a RomFS image), <mod>/exefs.nsp (a PFS0 of the ExeFS)
            root = segs[:-1]
            g = groups.setdefault(tuple(root), {'root': root, 'name_hint': None, 'files': [], 'ignored': []})
            g['files'].append((CONTAINERS[segs[-1].lower()], segs[-1].lower(), member))
            continue
        at = next((i for i, s in enumerate(segs[:-1]) if s.lower() in ANCHORS), None)
        if at is None:
            loose.append(member)
            continue
        anchor = ANCHORS[segs[at].lower()]
        root = segs[:at]
        if anchor in ('patches', 'nro_patches') and at + 2 < len(segs):
            key, name_hint, rel = tuple(root + [segs[at], segs[at + 1]]), segs[at + 1], '/'.join(segs[at + 2:])
        else:
            key, name_hint, rel = tuple(root), None, '/'.join(segs[at + 1:])
        g = groups.setdefault(key, {'root': root, 'name_hint': name_hint, 'files': [], 'ignored': []})
        c = classify(anchor, rel)
        if c:
            g['files'].append((c[0], c[1], member))
        else:
            g['ignored'].append(member)
    out = []
    for key, g in groups.items():
        tid = next((s for s in reversed(g['root']) if TID.match(s)), None)
        name = g['name_hint'] or next((s for s in reversed(g['root']) if not TID.match(s) and s.lower() not in GENERIC), None)
        meta = {}
        mj = '/'.join(g['root'] + ['mod.json'])
        if mj in entries:
            meta['_member'] = mj
        out.append({'name': name or fallback_name, 'title_id': tid.upper() if tid else None, 'files': g['files'],
                    'ignored': g['ignored'], 'meta': meta, 'root': '/'.join(g['root'])})
    roots = [g['root'] for g in groups.values()]
    leftovers = [m for m in loose if not any(m.startswith('/'.join(r) + '/') or not r for r in roots)] if groups else loose
    if groups:
        for m in leftovers:
            if m.rsplit('/', 1)[-1].lower() != 'mod.json':
                out[0]['ignored'].append(m)
        return out
    patches = [m for m in loose if m.lower().endswith(PATCH_EXTS)]
    if patches:      # a bare patch set: the files (with their set folders) are the patches
        prefix = os.path.commonprefix([m.split('/')[:-1] for m in patches])
        return [{'name': (prefix[-1] if prefix else fallback_name), 'title_id': None,
                 'files': [('patches', '/'.join(m.split('/')[len(prefix):]), m) for m in patches],
                 'ignored': [m for m in loose if m not in patches], 'meta': {}, 'root': '/'.join(prefix)}]
    if title is not None and loose:   # a bare RomFS tree: find the folder level whose entries are the game's
        top = title.romfs_top()
        best, best_hits = None, 0
        for d in range(0, 4):
            hits = sum(1 for m in loose if len(m.split('/')) > d and m.split('/')[d] in top)
            if hits > best_hits:
                best, best_hits = d, hits
        if best is not None and best_hits * 2 >= len(loose):
            prefix = os.path.commonprefix([m.split('/')[:best] for m in loose if len(m.split('/')) > best])
            files = [('romfs', '/'.join(m.split('/')[best:]), m) for m in loose if len(m.split('/')) > best and m.split('/')[:best] == prefix]
            name = next((s for s in reversed(prefix) if s.lower() not in GENERIC and s.lower() != 'romfs'), fallback_name)
            return [{'name': name, 'title_id': None, 'files': files, 'ignored': [m for m in loose if m.split('/')[:best] != prefix],
                     'meta': {}, 'root': '/'.join(prefix)}]
    raise ModError("These files are not in a mod layout PokoMac knows (romfs/, exefs/, exefs_patches/, cheats/ under a mod folder or "
                   "atmosphere/contents/<title id>/), and they are not the game's own RomFS files: it cannot tell where they go.")


