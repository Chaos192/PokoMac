def code_set(title, store, enabled):
    """The effective ExeFS of the enabled code mods: {module name: ('game'|'mod'|'patched', source path, [patches])}, or None when no
    code mod is on. Mods apply lowest first, so the first in the order wins where two replace or patch the same thing."""
    mods_code = [m for m in enabled if os.path.isdir(os.path.join(store.mod_dir(m['id']), 'exefs'))
                 or os.path.isdir(os.path.join(store.mod_dir(m['id']), 'patches'))]
    if not mods_code:
        return None, []
    files = {n: ('game', os.path.join(title.exefs, n)) for n in EXEFS_NAMES if os.path.isfile(os.path.join(title.exefs, n))}
    owner = {}
    conflicts = []
    for m in reversed(mods_code):
        ex = os.path.join(store.mod_dir(m['id']), 'exefs')
        for rel in walk_rel(ex):
            name = rel[:-5] if rel.endswith('.stub') else rel
            if name in owner:
                conflicts.append({'module': name, 'mods': [m['id'], owner[name]], 'winner': m['id']})
            owner[name] = m['id']
            if rel.endswith('.stub'):
                files.pop(name, None)
            else:
                files[name] = ('mod', os.path.join(ex, rel))
    plan = {}
    ranges = {}
    for name, (kind, path) in files.items():
        patches = []
        bid = nso_build_id(path) if name != 'main.npdm' else ''
        if bid:
            for m in reversed(mods_code):
                found = apply_ips.patches_for(os.path.join(store.mod_dir(m['id']), 'patches'), bid)
                for p in found:
                    for off, data in apply_ips.load_patch(p)[1]:
                        for other, a, b in ranges.get(name, []):
                            if other != m['id'] and off < b and a < off + len(data):
                                conflicts.append({'module': name, 'offset': '0x%x' % off, 'mods': [m['id'], other], 'winner': m['id']})
                                break
                        ranges.setdefault(name, []).append((m['id'], off, off + len(data)))
                patches += found
        plan[name] = ('patched' if patches else kind, path, patches)
    game = {n for n in EXEFS_NAMES if os.path.isfile(os.path.join(title.exefs, n))}
    if set(plan) == game and all(v[0] == 'game' for v in plan.values()):
        return None, []     # code mods whose patches name no module of this build change nothing
    dedup, seen = [], set()
    for c in conflicts:
        k = (c['module'], c.get('offset'), tuple(sorted(c['mods'])))
        if k not in seen:
            seen.add(k)
            dedup.append(c)
    return plan, dedup


def nro_patch_set(title, store, enabled):
    """The NROs the enabled mods' nro_patches change: [(SHA-256 of the original, RomFS path, patched image)] and the conflicts. Targets:
    the game's NROs and those the enabled mods' RomFS replaces or adds (the one served at a path: the highest mod's, else the game's).
    Patches apply lowest mod first, so the first in the order wins where two write the same bytes. Offsets count from the NRO's first
    byte (its header is part of its text), with nothing protected, as Atmosphère's ro patcher and Ryujinx (ApplyNroPatches) read them."""
    with_patches = [m for m in enabled if os.path.isdir(os.path.join(store.mod_dir(m['id']), 'nro_patches'))]
    if not with_patches:
        return [], []
    served = {rel: ('game', None) for rel, _b, _s in title.nros()}
    for m in reversed(enabled):
        rd = os.path.join(store.mod_dir(m['id']), 'romfs')
        for rel in walk_rel(rd):
            if rel.lower().endswith('.nro') and nro_info(os.path.join(rd, *rel.split('/'))):
                served[rel] = ('mod', os.path.join(rd, *rel.split('/')))
    out, conflicts = [], []
    for rel, (kind, path) in sorted(served.items()):
        if kind == 'game':
            data = title.nro_bytes(rel)
        else:
            with open(path, 'rb') as f:
                data = f.read()
        info = nro_info_bytes(data or b'')
        if not info:
            continue
        bid, sha = info
        buf = bytearray(data)
        owner = []
        applied = 0
        for m in reversed(with_patches):
            for p in apply_ips.patches_for(os.path.join(store.mod_dir(m['id']), 'nro_patches'), bid):
                for off, payload in apply_ips.load_patch(p)[1]:
                    end = min(off + len(payload), len(buf))
                    if end <= off:
                        continue
                    for other, a, b in owner:
                        if other != m['id'] and off < b and a < end:
                            conflicts.append({'module': rel, 'offset': '0x%x' % off, 'mods': [m['id'], other], 'winner': m['id']})
                            break
                    owner.append((m['id'], off, end))
                    buf[off:end] = payload[:end - off]
                    applied += 1
        if applied:
            out.append((sha, rel, bytes(buf)))
    return out, conflicts


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()


def code_stamp(plan):
    h = hashlib.sha256()
    for name in sorted(plan):
        kind, path, patches = plan[name]
        h.update(('%s\0%s\0%s\0' % (name, kind, sha256_file(path) if kind != 'game' else os.path.getsize(path))).encode())
        for p in patches:
            h.update(sha256_file(p).encode())
    return h.hexdigest()[:16]


def write_exefs(plan, out, sites=None, hook_lines=None):
    tmp = out + '.part'
    rmtree(tmp)
    os.makedirs(tmp)
    for name, (kind, path, patches) in plan.items():
        dst = os.path.join(tmp, name)
        if patches:
            apply_ips.patch_nso_many(path, patches, dst)
        else:
            link_or_copy(path, dst)
    for name, offs in (sites or {}).items():   # frame-step hook sites: offsets in the module, pkp_build adds its base
        write_text(os.path.join(tmp, name + '.sites'), '# PokoMac: frame-step hook sites of the enabled mods (mods.py resolve)\n'
                   + ''.join(('patch 0x%x %08x %08x\n' % (o, offs[o], NOP) if offs[o] is not None else '') + 'inline 0x%x\n' % o
                             for o in sorted(offs)))
    if hook_lines:   # the hook lines these sites were made for: the runtime registers these (engine_fields load_mod_fields), not the
        # ones a later change of the mods names before the game is built again (a replaced instruction is a nop in this build)
        write_text(os.path.join(tmp, 'frame_rate_hooks.txt'), '# PokoMac: the frame-step hooks this ExeFS was built with (mods.py '
                   'resolve). Generated: do not edit.\n' + ''.join(l + '\n' for l in hook_lines))
    rmtree(out)
    os.replace(tmp, out)


def rel_to(path, start):
    try:
        return fwd(os.path.relpath(path, start))
    except ValueError:        # another drive
        return fwd(path)


def resolve(title, store):
    mods = store.state['mods']
    enabled = [m for m in mods if m.get('enabled')]
    act = store.active
    os.makedirs(act, exist_ok=True)
    conflicts = []
    # RomFS: lowest first, each mod's deletions before its own folder
    lines = ['# PokoMac mod layers (mods.py resolve): lowest priority first. Generated: do not edit.']
    owner_of = {}
    gen_root = os.path.join(act, 'romfs_gen')
    rmtree(gen_root)
    before = store.state.get('romfs_mod_before')
    if before:
        lines.append('layer %s' % fwd(before))
    for m in reversed(enabled):
        d = store.mod_dir(m['id'])
        for rel in walk_rel(os.path.join(d, 'romfs_ext')):
            if rel.lower().endswith('.stub'):
                lines.append('delete /%s' % rel[:-5])
        rd = os.path.join(d, 'romfs')
        if os.path.isdir(rd):
            lines.append('layer %s' % rel_to(rd, act))
            for rel in walk_rel(rd):
                if rel in owner_of:
                    conflicts.append({'path': rel, 'mods': [m['id'], owner_of[rel]], 'winner': m['id']})
                owner_of[rel] = m['id']
        ips = [r for r in walk_rel(os.path.join(d, 'romfs_ext')) if r.lower().endswith('.ips')]
        if ips:
            g = os.path.join(gen_root, m['id'])
            for rel in ips:
                target = rel[:-4]
                dst = os.path.join(g, *target.split('/'))
                src_mod = os.path.join(rd, *target.split('/'))
                if os.path.isfile(src_mod):
                    os.makedirs(os.path.dirname(dst), exist_ok=True)
                    shutil.copyfile(src_mod, dst)
                elif not title.romfs_file(target, dst):
                    continue
                with open(dst, 'rb') as f:
                    buf = bytearray(f.read())
                apply_ips.apply_records(buf, apply_ips.load_patch(os.path.join(d, 'romfs_ext', *rel.split('/')))[1])
                with open(dst, 'wb') as f:
                    f.write(buf)
            if os.path.isdir(g):
                lines.append('layer %s' % rel_to(g, act))
    has_romfs = any(l.startswith(('layer ', 'delete ')) for l in lines[2 if before else 1:])   # a mod's, not only the Settings folder
    layers = os.path.join(act, 'romfs_layers.txt')
    write_text(layers, '\n'.join(lines) + '\n')
    # code
    plan, code_conflicts = code_set(title, store, enabled)
    conflicts += code_conflicts
    # frame-step hooks (docs/MODS.md "Frame-step hooks"): their sites are compiled into the game, so they make a code change of their own;
    # the effective ExeFS carries them as <module>.sites ("inline <offset>"), which pkp_build turns into the lift's site list
    hooks = frame_hooks(store, enabled, title.main_bid())
    hook_sites, hook_lines, last = {}, [], None
    for mid, b, hk in hooks:
        mod_name, off, _w = hook_site(hk)
        orig = hook_check(hk)[1]    # a hook that replaces its instruction: a nop there in the build ("patch" before its "inline")
        at = hook_sites.setdefault(mod_name, {})
        at[off] = orig if orig is not None else at.get(off)
        if (mid, b) != last:
            hook_lines += ['mod %s' % mid, 'build %s' % (b or '*')]
            last = (mid, b)
        hook_lines.append('hook %s' % hk)
    if hooks and not plan:
        plan = {n: ('game', os.path.join(title.exefs, n), []) for n in EXEFS_NAMES if os.path.isfile(os.path.join(title.exefs, n))}
    # NROs in the mods' RomFS (skyline plugins, replaced modules) are compiled by the build too (pkp_build prelift, nros.find mod_sources):
    # they are part of the code the next build makes, and the runtime never meets one it has to compile at its first load
    nros = []
    for m in enabled if NRO else []:
        rd = os.path.join(store.mod_dir(m['id']), 'romfs')
        for rel in walk_rel(rd):
            if rel.lower().endswith('.nro'):
                with open(os.path.join(rd, *rel.split('/')), 'rb') as f:
                    if f.read(0x14)[0x10:0x14] == b'NRO0':
                        nros.append((m['id'], rel, sha256_file(os.path.join(rd, *rel.split('/')))))
    # NRO patches (Atmosphère's nro_patches, offsets from the NRO's first byte, header included: ro applies them after the NRR check):
    # the patched image of every NRO a patch names, and the table the runtime's ro reads ([ro] nro_patches): original SHA-256 -> image
    nro_list, nro_conflicts = nro_patch_set(title, store, enabled)
    conflicts += nro_conflicts
    nro_table = os.path.join(act, 'nro_patches.tsv')
    nro_dir = os.path.join(act, 'nro')
    rmtree(nro_dir)
    rows = []
    for sha, rel, image in nro_list:
        dst = os.path.join(nro_dir, sha + '.nro')
        os.makedirs(nro_dir, exist_ok=True)
        with open(dst, 'wb') as f:
            f.write(image)
        rows.append('%s\t%s\t%s' % (sha, fwd(dst), rel))
        nros.append(('nro_patches', rel, hashlib.sha256(image).hexdigest()))
    write_text(nro_table, '# PokoMac: NRO patches of the mods (mods.py resolve; runtime ro.cpp [ro] nro_patches): original SHA-256, patched '
                          'image, RomFS path\n' + ''.join(r + '\n' for r in rows))
    code = {'stamp': '', 'exefs': ''}
    nro_stamp = hashlib.sha256(''.join('%s\0%s\0' % (r, h) for _m, r, h in sorted(nros)).encode()).hexdigest()[:16] if nros else ''
    if plan:
        stamp = code_stamp(plan)
        if hook_sites:   # the sites and the hook lines they serve: a changed hook is a changed build
            stamp = hashlib.sha256((stamp + ''.join('%s:%x:%s;' % (n, o, hook_sites[n][o]) for n in sorted(hook_sites)
                                                    for o in sorted(hook_sites[n])) + '\n'.join(hook_lines)).encode()).hexdigest()[:16]
        exefs = os.path.join(act, 'exefs-' + stamp)
        if not os.path.isdir(exefs):
            write_exefs(plan, exefs, hook_sites, hook_lines)
        code = {'stamp': stamp, 'exefs': fwd(exefs), 'modules': {n: v[0] for n, v in sorted(plan.items())}}
        if nro_stamp:
            code['stamp'] = hashlib.sha256((stamp + nro_stamp).encode()).hexdigest()[:16]
    elif nro_stamp:
        code = {'stamp': nro_stamp, 'exefs': ''}
    if nros:
        code['nros'] = [('patched ' + r) if m == 'nro_patches' else '%s/romfs/%s' % (m, r) for m, r, _h in sorted(nros)]
    keep = {os.path.basename(code['exefs']), os.path.basename(store.state.get('built', {}).get('exefs', '') or '')}
    for n in os.listdir(act):
        if n.startswith('exefs-') and n not in keep:
            rmtree(os.path.join(act, n))
    write_json(os.path.join(act, 'code.json'), code)
    # cheats
    main = title.main_bid()
    cheat_files = []
    for m in enabled:
        for rel in walk_rel(os.path.join(store.mod_dir(m['id']), 'cheats')):
            if apply_ips.bid_matches(rel.rsplit('/', 1)[-1][:-4], main):
                cheat_files.append(fwd(os.path.join(store.mod_dir(m['id']), 'cheats', rel)))
    cheats_list = os.path.join(act, 'cheats.txt')
    write_text(cheats_list, ''.join(p + '\n' for p in cheat_files))
    # frame rate: the enabled mods' blocks for this main, in order (the first mod's present_interval wins). The file keys each block to
    # the build it is for ("build", "*" for any), and names the present interval the mod put into pkp.ini ("present_interval", only while
    # that value is the mod's and not the player's own), so a game updated to another main after this resolve gets neither its fields nor
    # its present interval (runtime: engine_fields mod_interval_stale; nxnative frame-rate.md "A derived profile drops the frame step its
    # build lacks")
    fr_lines, fr_interval, fr_iv_mod, fr_mods = ["# PokoMac: the enabled mods' frame-rate fields (mods.py resolve; runtime "
                                                 'core/engine_fields.cpp, [mods] frame_rate). Generated: do not edit.'], None, None, []
    for m in enabled:
        fr, fr_errors = frame_rate_of(store.mod_dir(m['id']))
        if fr is None or fr_errors or (fr['build'] and not apply_ips.bid_matches(fr['build'], main)):
            continue
        if fr_interval is None and fr['present_interval']:
            fr_interval, fr_iv_mod = fr['present_interval'], m['id']
        fr_mods.append((m['id'], fr))
    ini0 = ini_read(title.ini_path) if store.write_ini else {}
    cur_iv0 = ini0.get(('display', 'present_interval')) or None    # an empty value is unset (the launcher's "as in Settings")
    iv_is_mods = bool(fr_interval) and store.write_ini and (cur_iv0 is None or cur_iv0 == store.state.get('present_interval_by_mods'))
    for mid, fr in fr_mods:
        own_iv = iv_is_mods and mid == fr_iv_mod
        if fr['fields'] or own_iv or fr['ue_fps_cvar'] or fr['hooks']:
            fr_lines.append('mod %s' % mid)
            fr_lines.append('build %s' % (fr['build'] or '*'))
            if own_iv:
                fr_lines.append('present_interval %s' % fr_interval)
            if fr['ue_fps_cvar']:
                fr_lines.append('ue_fps_cvar %s' % fr['ue_fps_cvar'])
            fr_lines += ['field %s' % x for x in fr['fields']]
            fr_lines += ['hook %s' % x for x in fr['hooks']]
    fr_path = os.path.join(act, 'frame_rate.txt')
    write_text(fr_path, '\n'.join(fr_lines) + '\n')
    write_json(os.path.join(act, 'conflicts.json'), conflicts)
    # the title's settings: [fs] romfs_mod and [cheats] mod_files ([fs] exefs_mod only after a build: `built`)
    if store.write_ini:
        ini = ini_read(title.ini_path)
        cur = ini.get(('fs', 'romfs_mod'), '')
        ours = rel_to(layers, title.dir)
        if cur and cur != ours and 'romfs_mod_before' not in store.state:
            store.state['romfs_mod_before'] = os.path.join(title.dir, cur) if not os.path.isabs(cur) else cur
            store.save()
            return resolve(title, store)     # the folder set in Settings becomes the lowest layer
        if has_romfs:
            ini_set(title.ini_path, 'fs', 'romfs_mod', ours)
        elif cur == ours:      # no mod changes the RomFS: the folder set in Settings (if any) is the mods folder again
            ini_set(title.ini_path, 'fs', 'romfs_mod', rel_to(before, title.dir) if before else None)
            if before:
                del store.state['romfs_mod_before']
                store.save()
        if rows:
            ini_set(title.ini_path, 'ro', 'nro_patches', rel_to(nro_table, title.dir))
        elif ini.get(('ro', 'nro_patches')):
            ini_set(title.ini_path, 'ro', 'nro_patches', None)
        if cheat_files:
            ini_set(title.ini_path, 'cheats', 'mod_files', rel_to(cheats_list, title.dir))
        elif ini.get(('cheats', 'mod_files')):
            ini_set(title.ini_path, 'cheats', 'mod_files', None)
        if len(fr_lines) > 1:
            ini_set(title.ini_path, 'mods', 'frame_rate', rel_to(fr_path, title.dir))
        elif ini.get(('mods', 'frame_rate')):
            ini_set(title.ini_path, 'mods', 'frame_rate', None)
        # [display] present_interval: a mod's choice while it is on; a value the player set himself (not by a mod) stays his
        cur_iv, mod_iv = ini.get(('display', 'present_interval')) or None, store.state.get('present_interval_by_mods')
        if fr_interval and (cur_iv is None or cur_iv == mod_iv):
            ini_set(title.ini_path, 'display', 'present_interval', fr_interval)
            if mod_iv != fr_interval:
                store.state['present_interval_by_mods'] = fr_interval
                store.save()
        elif not fr_interval and mod_iv:
            if cur_iv == mod_iv:
                ini_set(title.ini_path, 'display', 'present_interval', None)
            del store.state['present_interval_by_mods']
            store.save()
        if not plan and ini.get(('fs', 'exefs_mod')):
            pass   # the build that drops the code mods clears it (`built`), so the mapped modules keep matching the program until then
    return status(title, store, conflicts, code)


def status(title, store, conflicts=None, code=None):
    act = store.active
    if conflicts is None:
        conflicts = read_json(os.path.join(act, 'conflicts.json'), [])
    if code is None:
        code = read_json(os.path.join(act, 'code.json'), {'stamp': '', 'exefs': ''})
    built = store.state.get('built', {}).get('stamp', '')
    mods = []
    for m in store.state['mods']:
        m = dict(m)
        m['conflicts'] = [c for c in conflicts if m['id'] in c['mods']]
        mods.append(m)
    return {'title_id': title.title_id, 'build_ids': {n: b[:16] for n, b in title.modules.items()}, 'mods': mods,
            'store': fwd(store.dir), 'romfs_layers': fwd(os.path.join(act, 'romfs_layers.txt')), 'code': code,
            'code_changed': code.get('stamp', '') != built, 'conflicts': len(conflicts)}


def built(title, store):
    """A build with code.json's ExeFS finished: the runtime maps those modules ([fs] exefs_mod), or the game's own when no code mod."""
    code = read_json(os.path.join(store.active, 'code.json'), {'stamp': '', 'exefs': ''})
    store.state['built'] = {'stamp': code.get('stamp', ''), 'exefs': code.get('exefs', '')}
    store.save()
    if store.write_ini:
        ini_set(title.ini_path, 'fs', 'exefs_mod', rel_to(code['exefs'], title.dir) if code.get('exefs') else None)
    for n in os.listdir(store.active) if os.path.isdir(store.active) else []:
        if n.startswith('exefs-') and n != os.path.basename(code.get('exefs', '')):
            rmtree(os.path.join(store.active, n))
    return status(title, store)


